/**
 * Neon Postgres access shared by the Vercel function and local Bun server.
 * The schema is initialized once per serverless instance and is safe to retry.
 */

import { neon } from "@neondatabase/serverless";
import type { Booking, BookingStatus, QuietLevel, Room } from "../shared/types.ts";
import { seedIfEmpty } from "./seed.ts";

export interface RoomRow {
  id: number;
  name: string;
  floor: number;
  capacity: number;
  has_power: boolean;
  has_whiteboard: boolean;
  quiet_level: string;
}

export interface BookingRow {
  id: number;
  room_id: number;
  user_id: string | null;
  user_name: string;
  start_at: number | string;
  end_at: number | string;
  status: string;
  token: string;
  created_at: number | string;
  checked_in_at: number | string | null;
  released_at: number | string | null;
}

let queryPromise: ReturnType<typeof neon> | undefined;
let initialization: Promise<void> | undefined;

function getQuery(): ReturnType<typeof neon> {
  if (queryPromise) return queryPromise;
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) {
    throw new Error("DATABASE_URL is not configured");
  }
  queryPromise = neon(connectionString);
  return queryPromise;
}

export async function query<T = Record<string, unknown>>(
  statement: string,
  parameters: unknown[] = [],
): Promise<T[]> {
  return (await getQuery().query(statement, parameters)) as T[];
}

/**
 * Run a statement while holding a per-room transaction lock. The second query
 * gets a fresh READ COMMITTED snapshot after acquiring the lock.
 */
export async function queryForRoom<T = Record<string, unknown>>(
  roomId: number,
  statement: string,
  parameters: unknown[] = [],
): Promise<T[]> {
  const results = await getQuery().transaction((sql) => [
    sql.query("SELECT pg_advisory_xact_lock($1::bigint)", [roomId]),
    sql.query(statement, parameters),
  ]);
  return results[1] as T[];
}

export function ensureDatabase(): Promise<void> {
  initialization ??= initializeDatabase().catch((error: unknown) => {
    initialization = undefined;
    throw error;
  });
  return initialization;
}

async function initializeDatabase(): Promise<void> {
  await query("CREATE EXTENSION IF NOT EXISTS btree_gist");
  await query(`
    CREATE TABLE IF NOT EXISTS rooms (
      id             INTEGER PRIMARY KEY,
      name           TEXT NOT NULL,
      floor          INTEGER NOT NULL,
      capacity       INTEGER NOT NULL,
      has_power      BOOLEAN NOT NULL,
      has_whiteboard BOOLEAN NOT NULL,
      quiet_level    TEXT NOT NULL
    )
  `);
  await query(`
    CREATE TABLE IF NOT EXISTS bookings (
      id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      room_id       INTEGER NOT NULL REFERENCES rooms(id),
      user_id       TEXT,
      user_name     TEXT NOT NULL,
      start_at      BIGINT NOT NULL,
      end_at        BIGINT NOT NULL,
      status        TEXT NOT NULL CHECK (status IN ('pending','active','released','finished')),
      token         TEXT NOT NULL UNIQUE,
      created_at    BIGINT NOT NULL,
      checked_in_at BIGINT,
      released_at   BIGINT,
      CONSTRAINT bookings_no_time_overlap
        EXCLUDE USING gist (
          room_id WITH =,
          int8range(start_at, end_at, '[)') WITH &&
        )
        WHERE (status IN ('pending', 'active'))
    )
  `);
  await query("ALTER TABLE bookings ADD COLUMN IF NOT EXISTS user_id TEXT");
  await query("CREATE INDEX IF NOT EXISTS idx_bookings_room_time ON bookings (room_id, start_at, end_at)");
  await query("CREATE INDEX IF NOT EXISTS idx_bookings_token ON bookings (token)");
  await query(`
    CREATE TABLE IF NOT EXISTS waitlist (
      id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      room_id           INTEGER NOT NULL REFERENCES rooms(id),
      user_id           TEXT NOT NULL,
      user_name         TEXT NOT NULL,
      slot              INTEGER NOT NULL CHECK (slot IN (30, 60, 120)),
      created_at        BIGINT NOT NULL,
      status            TEXT NOT NULL CHECK (status IN ('waiting','offered','accepted','expired','cancelled')),
      offer_expires_at  BIGINT,
      booking_id        BIGINT REFERENCES bookings(id)
    )
  `);
  await query(`
    CREATE UNIQUE INDEX IF NOT EXISTS idx_waitlist_active_user_room
    ON waitlist (room_id, user_id)
    WHERE status IN ('waiting', 'offered')
  `);
  await query(`
    CREATE UNIQUE INDEX IF NOT EXISTS idx_waitlist_one_offer_per_room
    ON waitlist (room_id)
    WHERE status = 'offered'
  `);
  await query(`
    CREATE UNIQUE INDEX IF NOT EXISTS idx_waitlist_booking
    ON waitlist (booking_id)
    WHERE booking_id IS NOT NULL
  `);
  await query(`
    CREATE INDEX IF NOT EXISTS idx_waitlist_room_order
    ON waitlist (room_id, status, created_at, id)
  `);
  await query(`
    CREATE INDEX IF NOT EXISTS idx_waitlist_offer_expiry
    ON waitlist (offer_expires_at)
    WHERE status = 'offered'
  `);

  await seedIfEmpty();
}

export function toRoom(row: RoomRow): Room {
  return {
    id: Number(row.id),
    name: row.name,
    floor: Number(row.floor),
    capacity: Number(row.capacity),
    hasPower: row.has_power,
    hasWhiteboard: row.has_whiteboard,
    quietLevel: row.quiet_level as QuietLevel,
  };
}

export function toBooking(row: BookingRow): Booking {
  return {
    id: Number(row.id),
    roomId: Number(row.room_id),
    userName: row.user_name,
    startAt: Number(row.start_at),
    endAt: Number(row.end_at),
    status: row.status as BookingStatus,
    token: row.token,
    createdAt: Number(row.created_at),
    checkedInAt: row.checked_in_at === null ? null : Number(row.checked_in_at),
    releasedAt: row.released_at === null ? null : Number(row.released_at),
  };
}
